CREATE TABLE public.users (
 user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
 email text NOT NULL UNIQUE,
 role text NOT NULL DEFAULT 'resident' CHECK (role IN ('resident','admin')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.machines (
 machine_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 machine_name text NOT NULL UNIQUE,
 status text NOT NULL DEFAULT 'available'
  CHECK (status IN ('available','reserved','starting','in_use','out_of_service','offline')),
 location text NOT NULL
);
CREATE TABLE public.bookings (
 booking_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id uuid NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
 machine_id bigint NOT NULL REFERENCES public.machines(machine_id),
 slot_time timestamptz NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.fault_reports (
 report_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id uuid NOT NULL REFERENCES public.users(user_id),
 machine_id bigint NOT NULL REFERENCES public.machines(machine_id),
 description text NOT NULL CHECK (char_length(description) BETWEEN 5 AND 500),
 status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','pending','resolved')),
 reported_at timestamptz NOT NULL DEFAULT now()
);
